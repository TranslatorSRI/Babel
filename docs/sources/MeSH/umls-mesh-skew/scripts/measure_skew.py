"""Measure UMLS/MeSH version skew for several MeSH years against one UMLS download.

Runs the build's own generate_umls_mesh_skew_report() against each year's per-year MeSH RDF dump, so the
numbers are exactly what rule generate_umls_mesh_skew_report would report had mesh_year been that year. This
is the evidence behind config.yaml's umls_mesh_skew_max_missing_codes: matched versions should sit far below
it and a dump a year behind far above it.

Each dump is downloaded into --work-dir by the build's own fetch_mesh_nt() (from NLM's HTTPS site, checked
against its SHA-1 and normalized, about 120 MB compressed and 2 GB decompressed), and reused if already there.
Example (a few minutes, mostly downloads and the MRCONSO pass per year):

    uv run python docs/sources/MeSH/umls-mesh-skew/scripts/measure_skew.py \\
        --mrconso babel_downloads/UMLS/MRCONSO.RRF --umls-version 2026AA --mesh-years 2024 2025 2026 \\
        --work-dir data/umls-mesh-skew --output docs/sources/MeSH/umls-mesh-skew/README.md
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "..")))

from src.datahandlers.mesh import fetch_mesh_nt  # noqa: E402
from src.reports.umls_mesh_skew import generate_umls_mesh_skew_report  # noqa: E402


def fetch_mesh_nt_into(year, work_dir) -> str:
    """Download mesh{year}.nt into work_dir the way rule get_mesh does, reusing an earlier download."""
    nt_path = os.path.join(work_dir, f"mesh{year}.nt")
    if not os.path.exists(nt_path):
        fetch_mesh_nt(year, nt_path)
    return nt_path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mrconso", required=True, help="UMLS MRCONSO.RRF")
    parser.add_argument("--umls-version", required=True, help="The UMLS release MRCONSO.RRF is from, e.g. 2026AA")
    parser.add_argument("--mesh-years", nargs="+", required=True, help="MeSH years to measure")
    parser.add_argument("--work-dir", required=True, help="Where to download MeSH dumps and write JSON reports")
    parser.add_argument("--output", required=True, help="Markdown file to write")
    args = parser.parse_args()
    os.makedirs(args.work_dir, exist_ok=True)

    rows = []
    for year in args.mesh_years:
        nt_path = fetch_mesh_nt_into(year, args.work_dir)
        report_path = os.path.join(args.work_dir, f"umls_mesh_skew-{args.umls_version}-mesh{year}.json")
        report = generate_umls_mesh_skew_report(args.mrconso, nt_path, args.umls_version, year, report_path)
        by_type = report["missing_by_record_type"]
        rows.append(
            f"| {year} | {report['umls_msh_codes_missing_from_mesh']:,} "
            f"| {report['umls_msh_codes_missing_from_mesh_excluding_categories']:,} "
            f"| {by_type.get('D', 0):,} | {by_type.get('C', 0):,} | {by_type.get('Q', 0):,} | {by_type.get('U', 0):,} "
            f"| {report['umls_cuis_with_only_missing_msh_codes']:,} |"
        )

    with open(args.output, "w", encoding="utf-8") as outf:
        outf.write(
            f"""# UMLS/MeSH version skew

Generated by [`scripts/measure_skew.py`](scripts/measure_skew.py), which runs the build's own
`generate_umls_mesh_skew_report()` (`src/reports/umls_mesh_skew.py`) against UMLS {args.umls_version}'s
`MRCONSO.RRF` and each MeSH year's per-year RDF dump. A code is *missing* if it is an `SAB=MSH` code
in MRCONSO with no `rdfs:label` in the dump. `U` codes are the "(MeSH Category)" headings UMLS adds
itself, which are never in MeSH, so the build's check (`check_umls_mesh_skew`, limit
`umls_mesh_skew_max_missing_codes` in `config.yaml`) leaves them out.

| MeSH year | Missing codes | Missing, excluding `U` | `D` | `C` | `Q` | `U` | CUIs with only missing MSH codes |
|-----------|--------------:|-----------------------:|----:|----:|----:|----:|---------------------------------:|
"""
        )
        outf.write("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
